import type { Metadata } from "next";
import { bricolage, dmSans } from "./fonts";
import "./globals.css";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

/**
 * Marca <html> con la clase `js` antes de pintar (BD-025). Lo que se oculta o anima solo con JS
 * (paneles inactivos de Tabs, reveals de motion.css) depende de ella: sin JS todo queda visible.
 */
const MARK_JS = 'document.documentElement.classList.add("js")';

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    // suppressHydrationWarning: el script cambia la clase de <html> antes de que React hidrate.
    <html
      lang="en"
      className={`${bricolage.variable} ${dmSans.variable} h-full`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: MARK_JS }} />
      </head>
      <body className="flex min-h-full flex-col">{children}</body>
    </html>
  );
}
